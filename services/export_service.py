"""Export Service generating professional PDF, DOCX, TXT, CSV, XLSX, and JSON reports."""

import io
import json
from datetime import datetime
from typing import Dict, Any, List, Optional
import pandas as pd
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
import docx
from docx.shared import Inches, Pt, RGBColor
from config import APP_NAME

class ExportService:
    """Provides file export capabilities in PDF, DOCX, TXT, CSV, XLSX, and JSON."""

    # -------------------------------------------------------------
    # Summary Exports
    # -------------------------------------------------------------

    @staticmethod
    def export_summary_txt(filename: str, summary_data: Dict[str, Any]) -> bytes:
        """Exports document summary as plain text."""
        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        lines = [
            f"{'='*60}",
            f"{APP_NAME} - DOCUMENT ANALYSIS SUMMARY",
            f"{'='*60}",
            f"Document Title : {filename}",
            f"Generated On   : {timestamp}",
            f"Summary Mode   : {summary_data.get('mode', 'medium').capitalize()}",
            f"Word Count     : {summary_data.get('word_count', 0)}",
            f"{'-'*60}",
            "",
            "EXECUTIVE SUMMARY:",
            summary_data.get("summary", ""),
            "",
            f"{'-'*60}",
            "KEY TOPICS:",
            ", ".join(summary_data.get("key_topics", [])) or "None identified",
            "",
            "SIGNIFICANT DATES & FIGURES:",
        ]
        for item in summary_data.get("dates_and_figures", []):
            lines.append(f"• {item}")

        lines.extend(["", f"{'='*60}", f"Generated by {APP_NAME}"])
        return "\n".join(lines).encode("utf-8")

    @staticmethod
    def export_summary_docx(filename: str, summary_data: Dict[str, Any]) -> bytes:
        """Exports document summary as Microsoft Word (.docx)."""
        doc = docx.Document()

        # Title
        title_p = doc.add_paragraph()
        run = title_p.add_run(f"{APP_NAME} — Document Summary")
        run.bold = True
        run.font.size = Pt(20)
        run.font.color.rgb = RGBColor(30, 64, 175)

        # Metadata
        meta_p = doc.add_paragraph()
        meta_p.add_run(f"Document: {filename}\n")
        meta_p.add_run(f"Generated on: {datetime.now().strftime('%B %d, %Y - %I:%M %p')}\n")
        meta_p.add_run(f"Summary Mode: {summary_data.get('mode', 'medium').capitalize()} | Word Count: {summary_data.get('word_count', 0)}")

        doc.add_heading("Executive Summary", level=1)
        # Add summary paragraphs
        for para in summary_data.get("summary", "").split("\n\n"):
            if para.strip():
                doc.add_paragraph(para.strip())

        if summary_data.get("key_topics"):
            doc.add_heading("Key Topics", level=2)
            doc.add_paragraph(", ".join(summary_data["key_topics"]))

        if summary_data.get("dates_and_figures"):
            doc.add_heading("Significant Dates & Figures", level=2)
            for item in summary_data["dates_and_figures"]:
                doc.add_paragraph(item, style='List Bullet')

        buf = io.BytesIO()
        doc.save(buf)
        return buf.getvalue()

    @staticmethod
    def export_summary_pdf(filename: str, summary_data: Dict[str, Any]) -> bytes:
        """Exports document summary as a formatted PDF."""
        buf = io.BytesIO()
        doc = SimpleDocTemplate(buf, pagesize=letter, rightMargin=40, leftMargin=40, topMargin=40, bottomMargin=40)
        styles = getSampleStyleSheet()

        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Heading1"],
            fontSize=18,
            leading=22,
            textColor=colors.HexColor("#1E40AF"),
            spaceAfter=6
        )
        meta_style = ParagraphStyle(
            "DocMeta",
            parent=styles["Normal"],
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#64748B"),
            spaceAfter=15
        )
        heading_style = ParagraphStyle(
            "SecHeading",
            parent=styles["Heading2"],
            fontSize=13,
            leading=16,
            textColor=colors.HexColor("#0F172A"),
            spaceBefore=12,
            spaceAfter=6
        )
        body_style = ParagraphStyle(
            "Body",
            parent=styles["Normal"],
            fontSize=10,
            leading=14,
            textColor=colors.HexColor("#334155"),
            spaceAfter=8
        )

        elements = [
            Paragraph(f"{APP_NAME} — Document Analysis Report", title_style),
            Paragraph(f"<b>Document:</b> {filename} | <b>Date:</b> {datetime.now().strftime('%Y-%m-%d %H:%M')} | <b>Mode:</b> {summary_data.get('mode', 'medium').capitalize()}", meta_style),
            HRFlowable(width="100%", thickness=1, color=colors.HexColor("#E2E8F0"), spaceAfter=12),
            Paragraph("Executive Summary", heading_style)
        ]

        for p in summary_data.get("summary", "").split("\n\n"):
            if p.strip():
                # Escape html-like tags
                safe_text = p.strip().replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                elements.append(Paragraph(safe_text, body_style))

        if summary_data.get("dates_and_figures"):
            elements.append(Spacer(1, 10))
            elements.append(Paragraph("Key Dates, Numbers & Findings", heading_style))
            for item in summary_data["dates_and_figures"]:
                safe_item = item.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                elements.append(Paragraph(f"• {safe_item}", body_style))

        doc.build(elements)
        return buf.getvalue()

    # -------------------------------------------------------------
    # Chat Conversation Exports
    # -------------------------------------------------------------

    @staticmethod
    def export_chat_txt(messages: List[Dict[str, Any]], conv_title: str = "Chat Session") -> bytes:
        """Exports conversation history to TXT."""
        lines = [
            f"{'='*60}",
            f"{APP_NAME} — CHAT TRANSCRIPT",
            f"Title: {conv_title}",
            f"Exported: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
            f"{'='*60}\n"
        ]
        for m in messages:
            role = "USER" if m["role"] == "user" else "ASSISTANT"
            lines.append(f"[{role} - {m.get('created_at', '')}]")
            lines.append(m["content"])
            if m.get("citations"):
                lines.append("Sources Cited:")
                for c in m["citations"]:
                    lines.append(f"  * {c.get('filename', '')} (Page {c.get('page_number', 1)})")
            lines.append("\n" + "-"*40 + "\n")

        return "\n".join(lines).encode("utf-8")

    @staticmethod
    def export_chat_pdf(messages: List[Dict[str, Any]], conv_title: str = "Chat Session") -> bytes:
        """Exports conversation history to PDF."""
        buf = io.BytesIO()
        doc = SimpleDocTemplate(buf, pagesize=letter, rightMargin=40, leftMargin=40, topMargin=40, bottomMargin=40)
        styles = getSampleStyleSheet()

        title_style = ParagraphStyle("ConvTitle", parent=styles["Heading1"], fontSize=16, textColor=colors.HexColor("#1E40AF"))
        user_style = ParagraphStyle("UserMsg", parent=styles["Normal"], fontSize=10, textColor=colors.HexColor("#1E3A8A"), fontName="Helvetica-Bold", spaceBefore=8)
        asst_style = ParagraphStyle("AsstMsg", parent=styles["Normal"], fontSize=10, leading=14, textColor=colors.HexColor("#1F2937"), spaceAfter=8)
        cite_style = ParagraphStyle("CiteMsg", parent=styles["Normal"], fontSize=8, textColor=colors.HexColor("#64748B"))

        elements = [
            Paragraph(f"{APP_NAME} — Q&amp;A Transcript: {conv_title}", title_style),
            HRFlowable(width="100%", thickness=1, color=colors.HexColor("#CBD5E1"), spaceAfter=12)
        ]

        for m in messages:
            role_label = "User" if m["role"] == "user" else "AskFile AI"
            content = m["content"].replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\n", "<br/>")
            elements.append(Paragraph(f"<b>{role_label}:</b>", user_style))
            elements.append(Paragraph(content, asst_style))

            if m.get("citations"):
                c_str = ", ".join([f"{c.get('filename')} (p.{c.get('page_number')})" for c in m["citations"]])
                elements.append(Paragraph(f"<i>Sources: {c_str}</i>", cite_style))
            elements.append(Spacer(1, 6))

        doc.build(elements)
        return buf.getvalue()

    # -------------------------------------------------------------
    # Information Extraction Exports (CSV, XLSX, JSON)
    # -------------------------------------------------------------

    @staticmethod
    def export_extraction_json(extraction_data: Dict[str, Any]) -> bytes:
        """Exports extracted entities as formatted JSON."""
        return json.dumps(extraction_data, indent=2, ensure_ascii=False).encode("utf-8")

    @staticmethod
    def export_extraction_csv(extraction_data: Dict[str, Any]) -> bytes:
        """Flattens extracted entities into a clean tabular CSV."""
        rows = []
        category_map = {
            "emails": "Email Address",
            "phones": "Phone Number",
            "financials": "Financial / Currency",
            "dates": "Date",
            "organizations": "Organization",
            "person_names": "Person Name",
            "headings": "Heading / Section",
            "objectives": "Document Objective",
            "conclusions": "Conclusion",
            "action_items": "Action Item",
            "key_terms": "Key Term"
        }
        for key, label in category_map.items():
            items = extraction_data.get(key, [])
            for item in items:
                rows.append({"Category": label, "Extracted Value": item})

        df = pd.DataFrame(rows)
        return df.to_csv(index=False).encode("utf-8")

    @staticmethod
    def export_extraction_xlsx(extraction_data: Dict[str, Any]) -> bytes:
        """Exports extracted entities into Excel (.xlsx) with clean formatting."""
        rows = []
        category_map = {
            "emails": "Email Address",
            "phones": "Phone Number",
            "financials": "Financial / Currency",
            "dates": "Date",
            "organizations": "Organization",
            "person_names": "Person Name",
            "headings": "Heading / Section",
            "objectives": "Document Objective",
            "conclusions": "Conclusion",
            "action_items": "Action Item",
            "key_terms": "Key Term"
        }
        for key, label in category_map.items():
            items = extraction_data.get(key, [])
            for item in items:
                rows.append({"Category": label, "Extracted Value": item})

        df = pd.DataFrame(rows)
        buf = io.BytesIO()
        with pd.ExcelWriter(buf, engine="openpyxl") as writer:
            df.to_excel(writer, sheet_name="Extracted Entities", index=False)
        return buf.getvalue()
